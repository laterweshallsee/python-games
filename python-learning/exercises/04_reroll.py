import random

#генерю список з 5 елементами від 1 до 6 (поки не зовсім викупаю точно як це працює)

print(input('press enter: '))

hand = [random.randint(1, 6)  for _ in range(5)]

num = 0

for i in hand:
    num += 1
    print('№', num, ":", i)

#запитую які кубики гравець хоче замінити і х в свою чергу приймає значення кожного елемента послідовно, але спочатку
#як строку, а потім я задаю йому значення інт тобто числа і віднімаю одиницю бо відлік елементів починається з 0
#і задаю елементу на тому місці значення від 1 до 6 (2 raza)

for _ in range(2):
    change = input('які кубики бажаєте замінити? ').split()

    for x in change:
        x = int(x) - 1
        hand[x] = random.randint(1, 6)

    num = 0

    for i in hand:
        num += 1
        print('№', num, ":", i)


